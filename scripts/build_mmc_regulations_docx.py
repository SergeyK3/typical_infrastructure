    if not TEMPLATE.is_file():
        raise SystemExit(f"Template not found: {TEMPLATE}")
    GDRIVE_HOSP_DIR.mkdir(parents=True, exist_ok=True)
    created: list[str] = []
    for spec in SPECS:
        for out_dir in (DOC_DIR, GDRIVE_HOSP_DIR):
            make_doc(spec, out_dir / spec.filename)
        created.append(spec.filename)
    print(f"Created {len(created)} regulation drafts in {DOC_DIR} and {GDRIVE_HOSP_DIR}:")
    for name in created:
        print(f"  - {name}")


