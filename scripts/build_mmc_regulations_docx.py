def reg_code(code: str) -> str:
    return f"REG_{code}_V1"


def set_para(para, text: str) -> None:
    if not para.runs:
        para.text = text
        return
    para.runs[0].text = text
    for run in para.runs[1:]:
        run.text = ""


def fill_table(table, rows: list[list[str]]) -> None:
    while len(table.rows) > len(rows):
        table._tbl.remove(table.rows[-1]._tr)
    for ri, row_data in enumerate(rows):
        while len(table.rows) <= ri:
            table.add_row()
        row = table.rows[ri]
        for ci, value in enumerate(row_data):
            while len(row.cells) <= ci:
                row.add_cell()
            set_cell_text(row.cells[ci], value)
        for ci in range(len(row_data), len(row.cells)):
            set_cell_text(row.cells[ci], "")


