def make_doc(spec: RegulationSpec, out: Path) -> None:
    shutil.copy2(TEMPLATE, out)
    doc = Document(str(out))

    meta = {
        "Код регламента": reg_code(spec.position_code),
        "Версия": "V1",
        "Подразделение": spec.department,
        "Статус": "Черновик",
        "Должность": f"{spec.title_ru}\n({spec.position_code})",
        "Дата": TODAY,
        "Область применения": spec.scope,
        "Основание": f"{spec.source_doc}; {GDRIVE}",
    }
    for row in doc.tables[0].rows:
        k1 = row.cells[0].text.strip()
        if k1 in meta:
            set_cell_text(row.cells[1], meta[k1])
        if len(row.cells) > 2:
            k2 = row.cells[2].text.strip()
            if k2 in meta:
                set_cell_text(row.cells[3], meta[k2])

    set_para(doc.paragraphs[1], spec.title_ru)

    legal1 = spec.intro
    reports = (
        f"Должность подчиняется {spec.chief}, а также директору медицинского центра "
        f"в части административных и организационных вопросов."
    )
    legal2 = (
        "Сотрудник действует в пределах настоящего регламента, локальных протоколов клиники, "
        "стандартов оказания медицинской помощи, правил медицинской документации, "
        "инфекционного контроля, охраны труда и защиты персональных данных пациентов."
    )

    content = [
        legal1,
        reports,
        legal2,
        spec.goal,
        *spec.results,
        *spec.responsibilities,
        spec.ckp,
        *spec.powers,
        *spec.accountability,
        *spec.qualifications,
        *spec.style,
        *spec.artifacts,
    ]

    idx = 0
    skip_until_kpi = False
    for pi, para in enumerate(doc.paragraphs):
        if pi == 1:
            continue
        text = para.text.strip()
        if text.startswith("7.") and "навыки" in text.lower():
            skip_until_kpi = True
            continue
        if skip_until_kpi:
            if text.startswith("8.") and "KPI" in text.upper():
                skip_until_kpi = False
            continue
        if not text or text.startswith(
            (
                "РЕГЛАМЕНТ",
                "1.",
                "2.",
                "3.",
                "4.",
                "5.",
                "6.",
                "8.",
                "9.",
                "10.",
                "11.",
                "12.",
                "13.",
                "Согласование",
            )
        ):
            continue
        if idx < len(content):
            set_para(para, content[idx])
            idx += 1

    fill_table(
        doc.tables[1],
        [["Период", "Основные действия", "Результат"], *default_cycle(spec.cycle_focus)],
    )
    setup_section7_skills(doc, spec.position_code)

    kpi_table = next(
        t
        for t in doc.tables
        if t.rows and "показатель" in " ".join(c.text.lower() for c in t.rows[0].cells)
    )
    approvers_table = doc.tables[-1]
    kpi_rows = [["№", "Показатель", "Как измеряется", "Целевой ориентир"]]
    for row in spec.kpis:
        kpi_rows.append(list(row))
    fill_table(kpi_table, kpi_rows)
    fill_table(
        approvers_table,
        [["Роль", "ФИО / подпись", "Примечание"], *spec.approvers],
    )
    set_paragraph_after_heading(doc, "8.", "KPI", spec.kpi_intro)
    format_regulation_tables(doc)
    doc.save(str(out))


